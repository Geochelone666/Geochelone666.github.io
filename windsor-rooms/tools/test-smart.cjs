'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),zlib=require('node:zlib'),path=require('node:path');
const {freeWindows,eventsForDate,rankCandidates,evaluateRoom,validISODate}=require('../smart.js');
const at=n=>path.join(__dirname,'..',n);
const data=n=>JSON.parse(zlib.gunzipSync(fs.readFileSync(at(n))));
const fall=data('data.json.gz'),winter=data('winter2027.json.gz');
const event=(from,to)=>['class','Erie Hall','3119','Monday','','2026-09-10','2026-12-22',from,to,'COMP 1410','LAB','51','3211','Test'];
assert.deepEqual(freeWindows([event('09:00','10:00'),event('09:30','11:00'),event('11:00','12:00')],'08:00','13:00',60),[{start:'08:00',end:'09:00',minutes:60},{start:'12:00',end:'13:00',minutes:60}]);
assert.deepEqual(freeWindows([event('09:00','10:00')],'09:00','10:00',60),[]);
assert.deepEqual(freeWindows([],'15:00','14:00',60),[]);
assert.equal(validISODate('2027-01-04'),true);
assert.equal(validISODate('2027-02-30'),false);
assert.equal(eventsForDate([event('09:00','10:00')],'2026-11-23').length,1);
assert.equal(eventsForDate([event('09:00','10:00')],'2026-11-24').length,0);
assert.equal(fall.info.compInstructorsMapped,83);
assert.equal(fall.info.exams,806);
assert.equal(fall.compLab.sites.length,12);
assert.equal(fall.hardware.labs.length,21);
assert.equal(winter.info.verifiedDetailCOMPcourses,61);
assert.equal(winter.info.indexedCOMPcourses,61);
assert.equal(winter.info.coverage,'COMP_ONLY');
assert.equal(winter.compLab.sites.length,9);
assert.equal(winter.compLab.summary.uniqueLABSections,30);
assert.equal(winter.info.compInstructorsMapped,73);
assert.equal(winter.info.exams,0);
const from={date:'2027-01-11',from:'13:00',to:'16:00',minMinutes:60};
const candidates=rankCandidates(winter,winter.compLab.sites.map(x=>x.building+'|'+x.room),from);
assert.equal(candidates.length,9);
assert(!candidates.some(x=>x.status==='candidate'),'No Winter COMP-only venue can be advertised as free');
assert(candidates.some(x=>x.status==='partial-coverage'));
const room=evaluateRoom(winter,'Erie Hall|3119',from);
assert.equal(room.verified,true);
assert.notEqual(room.status,'candidate');
console.log('WINDSOR_ROOMS_SMART_TESTS_PASS',JSON.stringify({fallRooms:fall.info.rooms,winterRooms:winter.info.rooms,fallLessons:fall.info.classes,winterLessons:winter.info.classes,winterKnownProfessors:winter.info.compInstructorsMapped}));
